    window.openMysteryBox = function() {
        var totalWeight = BOX_PRIZES.reduce(function(s, p) { return s + p.weight; }, 0);
        var r = Math.random() * totalWeight;
        var prize = BOX_PRIZES[0].credits;
        for (var i = 0; i < BOX_PRIZES.length; i++) {
            r -= BOX_PRIZES[i].weight;
            if (r <= 0) { prize = BOX_PRIZES[i].credits; break; }
        }
        document.getElementById('eg-box-open').disabled = true;
        var icon = document.getElementById('eg-box-icon');
        icon.classList.remove('shaking');
        icon.textContent = '🎉';
        egAddCredits(prize);
        egConfetti();
        egToast(et('boxToast').replace('{n}', prize));
        setTimeout(function() { egCloseModal('eg-box-modal'); }, 1200);
    };

    // --- in-room text chat ---
    var lastChatTime = 0;

    window.sendRoomChat = function() {
        var user = auth.currentUser;
        var room = getActiveRoom();
        var input = document.getElementById('room-chat-input');
        if (!user || !room || !input) return;
        var text = input.value.trim().slice(0, 100);
        if (!text) return;
        var now = Date.now();
        if (now - lastChatTime < 5000) return;
        lastChatTime = now;
        input.value = '';
        db.collection('room_events').add({
            roomId: room.id,
            uid: user.uid,
            displayName: user.displayName || '',
            photoURL: user.photoURL || '',
            eventType: 'chat',
            detail: text,
            timestamp: firebase.firestore.FieldValue.serverTimestamp()
        }).catch(function(err) { console.error('send chat:', err); });
    };

