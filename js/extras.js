    function renderSpinWheel() {
        document.getElementById('eg-spin-title').textContent = et('spinTitle');
        document.getElementById('eg-spin-sub').textContent = et('spinSub');
        var btn = document.getElementById('eg-spin-btn');
        btn.textContent = et('spinBtn');
        btn.disabled = false;
        var wheel = document.getElementById('eg-spin-wheel');
        wheel.style.transition = 'none';
        wheel.style.transform = 'rotate(0deg)';
        var labels = document.getElementById('eg-spin-labels');
        labels.innerHTML = '';
        SPIN_PRIZES.forEach(function(p, i) {
            var span = document.createElement('span');
            span.className = 'spin-label';
            span.style.transform = 'rotate(' + (i * 45 + 22.5) + 'deg) translateY(-58px)';
            span.textContent = p;
            labels.appendChild(span);
        });
    }

    window.doDailySpin = function() {
        if (spinDone || !egUser) return;
        spinDone = true;
        document.getElementById('eg-spin-btn').disabled = true;
        var idx = Math.floor(Math.random() * SPIN_PRIZES.length);
        var prize = SPIN_PRIZES[idx];
        // Pointer sits at the top; rotate the wheel so segment idx lands under it
        var target = 360 * 5 - (idx * 45 + 22.5);
        var wheel = document.getElementById('eg-spin-wheel');
        var labels = document.getElementById('eg-spin-labels');
        wheel.style.transition = 'transform 3.5s cubic-bezier(0.12, 0.8, 0.2, 1)';
        labels.style.transition = 'transform 3.5s cubic-bezier(0.12, 0.8, 0.2, 1)';
        requestAnimationFrame(function() {
            wheel.style.transform = 'rotate(' + target + 'deg)';
            labels.style.transform = 'rotate(' + target + 'deg)';
        });
        db.collection('daily_spin').doc(egUser.uid).set({
            uid: egUser.uid,
            lastSpinDate: getDayKey(),
            lastPrize: prize,
            updatedAt: firebase.firestore.FieldValue.serverTimestamp()
        }).catch(function(err) { console.error('spin save:', err); });
        setTimeout(function() {
            egAddCredits(prize);
            egConfetti();
            egToast(et('spinToast').replace('{n}', prize));
            egCloseModal('eg-spin-modal');
            labels.style.transition = 'none';
            labels.style.transform = 'rotate(0deg)';
        }, 3800);
    };

